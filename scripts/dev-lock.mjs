// Turns the private dev mode password into a publishable lock: src/dev-lock.js.
//
//   npm run dev-lock
//
// Reads DEV_PASSWORD from the git-ignored ./dev.local.mjs, picks a fresh random
// 16-byte salt, derives a 32-byte key with PBKDF2-SHA256 (310,000 iterations) and
// writes { salt, iterations, hash } as base64. The salt and hash are safe to
// commit; the plaintext never leaves dev.local.mjs.
import fs from 'node:fs';
import crypto from 'node:crypto';

const ITERATIONS = 310000;
const root = new URL('../', import.meta.url);
const priv = new URL('dev.local.mjs', root);

if (!fs.existsSync(priv)) {
  console.error('Missing dev.local.mjs. Create it at the repo root with:\n  export const DEV_PASSWORD = \'your password\';');
  process.exit(1);
}
const { DEV_PASSWORD } = await import(priv.href);
if (typeof DEV_PASSWORD !== 'string' || DEV_PASSWORD.length < 8) {
  console.error('DEV_PASSWORD in dev.local.mjs must be a string of at least 8 characters.');
  process.exit(1);
}

const salt = crypto.randomBytes(16);
const hash = crypto.pbkdf2Sync(DEV_PASSWORD, salt, ITERATIONS, 32, 'sha256');
const out = `/* Daily Ascent — dev mode lock. GENERATED by \`npm run dev-lock\`; do not edit by hand.
   PBKDF2-SHA256 of the dev password from the private, git-ignored dev.local.mjs.
   Only the salt and the derived hash live here: both are safe to publish. */
var DA_DEV_LOCK = { salt: '${salt.toString('base64')}', iterations: ${ITERATIONS}, hash: '${hash.toString('base64')}' };
`;
fs.writeFileSync(new URL('src/dev-lock.js', root), out);
console.log('wrote src/dev-lock.js (PBKDF2-SHA256, ' + ITERATIONS.toLocaleString('en-US') + ' iterations)');
